function [Population, Z] = SearchOneGeneration_D(Problem, Population, W, B, T, Z, actionID, history, gensSinceChange)
% SearchOneGeneration_D
% -------------------------------------------------------------------------
% Steady-state search module redesigned by borrowing the core idea of SGEA:
%   1) generate ONE offspring at a time;
%   2) insert it through environmental selection;
%   3) use archive-assisted mating softly;
%   4) reinsert elitists at the end of the generation.
%
% The interface is kept unchanged so that it can directly replace the
% current file in MARL_AC_D.
%
% Agent 2 actions (all actions only change offspring generation; offspring
% insertion is unified by EnvironmentalSelection_D):
%   1 - Local steady search (current population only, mild exploitation)
%   2 - Archive-assisted GA search
%   3 - Population-only DE exploration
%   4 - Archive/history-guided DE search
% -------------------------------------------------------------------------

    if nargin < 9
        gensSinceChange = 0;
    end
    if nargin < 8 || isempty(history)
        history = struct('count', 0, 'decs', {{}}, 'decCenters', {{}});
    end

    N = length(Population);
    if N <= 1
        return;
    end

    % Build a current archive and fitness as in SGEA.
    [Population, Archive, Fitness] = EnvironmentalSelection_D(Population, N);
    Elitists = Population;

    for i = 1 : N
        Offspring = localGenerateOffspringSGEA( ...
            Problem, Population, Archive, Fitness, B, T, i, actionID, history, gensSinceChange);

        Z = min(Z, Offspring.obj);
        [Population, Archive, Fitness] = EnvironmentalSelection_D([Population, Offspring], N);
    end

    % Elitist reinsertion, exactly in the spirit of SGEA.
    [Population, ~, ~] = EnvironmentalSelection_D([Population, Elitists], N);
end

%% ========================= Local helper functions ========================

function Offspring = localGenerateOffspringSGEA(Problem, Population, Archive, Fitness, B, T, i, actionID, history, gensSinceChange)
    N = length(Population);
    if isempty(Archive)
        Archive = Population;
    end

    cfg = localGetParamConfig(actionID, gensSinceChange);

    switch actionID
        case 1
            % Local steady search:
            % parents are mainly drawn from the neighborhood, and offspring is
            % generated by a mild GA operator, which is close to SGEA's
            % fine-grained search behavior.
            localPool = unique([i, B(i, 1:min(T, size(B, 2)))]);
            localFit  = Fitness(localPool);
            if rand < cfg.localBias
                [~, sortedIdx] = sort(localFit, 'ascend');
                keepTop = max(2, ceil(0.6 * numel(localPool)));
                localPool = localPool(sortedIdx(1:keepTop));
                localFit = Fitness(localPool);
            end

            p1 = localPool(localTournament(localFit));
            p2 = localPool(localTournament(localFit));
            while p2 == p1 && numel(localPool) > 1
                p2 = localPool(localTournament(localFit));
            end
            Offspring = OperatorGAhalf(Problem, [Population(p1), Population(p2)]);

        case 2
            % Archive-assisted GA search:
            % current population contributes one parent, archive contributes
            % the other, which follows SGEA's soft archive injection idea.
            if cfg.localBias >= 0.6
                [~, rankPop] = sort(Fitness, 'ascend');
                topK = max(2, ceil(0.5 * N));
                p1 = rankPop(randi(topK));
            else
                p1 = localTournament(Fitness);
            end

            if cfg.guideWeight >= 0.35 && ~isempty(Archive)
                A = Archive.decs;
                d = sum((A - repmat(Population(p1).dec, size(A, 1), 1)).^2, 2);
                [~, rankA] = sort(d, 'ascend');
                nearK = max(1, ceil(0.4 * numel(rankA)));
                a1 = rankA(randi(nearK));
            else
                a1 = randi(length(Archive));
            end

            Offspring = OperatorGAhalf(Problem, [Population(p1), Archive(a1)]);

        case 3
            % Population-only DE exploration:
            % still one-offspring-at-a-time, but slightly more exploratory.
            idx = randperm(N, min(3, N));
            while numel(idx) < 3
                idx = [idx, randi(N)]; %#ok<AGROW>
            end
            x1 = Population(idx(1)).dec;
            x2 = Population(idx(2)).dec;
            x3 = Population(idx(3)).dec;

            % Mildly increase exploration shortly after a change.
            F  = cfg.F + 0.08 * min(gensSinceChange / 5, 1);
            CR = cfg.CR;
            dec = localDERandOne(x1, x2, x3, Problem.lower, Problem.upper, F, CR);
            dec = localPolynomialMutation(dec, Problem.lower, Problem.upper, cfg.etaM);
            Offspring = Problem.Evaluation(dec);

        case 4
            % Archive/history-guided DE search:
            % use current population as the base, and guide it softly by the
            % current archive or the most recent history memory.
            target = Population(localTournament(Fitness)).dec;
            r = randperm(N, min(2, N));
            while numel(r) < 2
                r = [r, randi(N)]; %#ok<AGROW>
            end
            r1 = Population(r(1)).dec;
            r2 = Population(r(2)).dec;

            if ~isempty(Archive)
                guide = Archive(randi(length(Archive))).dec;
            elseif history.count >= 1 && ~isempty(history.decs{history.count})
                H = history.decs{history.count};
                guide = H(randi(size(H, 1)), :);
            else
                guide = Population(randi(N)).dec;
            end

            if history.count >= 2
                drift = history.decCenters{history.count} - history.decCenters{history.count - 1};
            else
                drift = zeros(1, numel(target));
            end
            driftWeight = min(gensSinceChange / 6, 1);
            guide = guide + cfg.guideWeight * driftWeight * drift;

            dec = localGuidedDE(target, r1, r2, guide, Problem.lower, Problem.upper, cfg.F, cfg.CR);
            dec = localPolynomialMutation(dec, Problem.lower, Problem.upper, cfg.etaM);
            Offspring = Problem.Evaluation(dec);

        otherwise
            p1 = localTournament(Fitness);
            p2 = localTournament(Fitness);
            while p2 == p1 && N > 1
                p2 = localTournament(Fitness);
            end
            Offspring = OperatorGAhalf(Problem, [Population(p1), Population(p2)]);
    end
end

function idx = localTournament(Fitness)
    n = numel(Fitness);
    if n == 1
        idx = 1;
        return;
    end
    a = randi(n);
    b = randi(n);
    if Fitness(a) <= Fitness(b)
        idx = a;
    else
        idx = b;
    end
end

function child = localDERandOne(r1, r2, r3, lower, upper, F, CR)
    D = numel(r1);
    v = r1 + F * (r2 - r3);

    child = r1;
    jrand = randi(D);
    mask = rand(1, D) < CR;
    mask(jrand) = true;
    child(mask) = v(mask);
    child = localBoundRepair(child, lower, upper);
end

function child = localGuidedDE(x, r1, r2, guide, lower, upper, F, CR)
    D = numel(x);
    v = x + 0.30 * (guide - x) + F * (r1 - r2);

    child = x;
    jrand = randi(D);
    mask = rand(1, D) < CR;
    mask(jrand) = true;
    child(mask) = v(mask);
    child = localBoundRepair(child, lower, upper);
end

function y = localPolynomialMutation(x, lower, upper, etaM)
    D = numel(x);
    proM = 1 / D;
    y = x;

    for j = 1:D
        if rand < proM
            delta1 = (y(j) - lower(j)) / (upper(j) - lower(j) + 1e-12);
            delta2 = (upper(j) - y(j)) / (upper(j) - lower(j) + 1e-12);
            rnd = rand;
            mutPow = 1 / (etaM + 1);

            if rnd <= 0.5
                xy = 1 - delta1;
                val = 2 * rnd + (1 - 2 * rnd) * (xy^(etaM + 1));
                deltaq = val^mutPow - 1;
            else
                xy = 1 - delta2;
                val = 2 * (1 - rnd) + 2 * (rnd - 0.5) * (xy^(etaM + 1));
                deltaq = 1 - val^mutPow;
            end

            y(j) = y(j) + deltaq * (upper(j) - lower(j));
        end
    end

    y = localBoundRepair(y, lower, upper);
end

function X = localBoundRepair(X, lower, upper)
    X = min(max(X, lower), upper);
end

function cfg = localGetParamConfig(actionID, gensSinceChange)
    switch actionID
        case 1
            cfg.F = 0.35;
            cfg.CR = 0.85;
            cfg.etaM = 28;
            cfg.guideWeight = 0.20;
            cfg.localBias = 0.75;
        case 2
            cfg.F = 0.50;
            cfg.CR = 0.75;
            cfg.etaM = 20;
            cfg.guideWeight = 0.30;
            cfg.localBias = 0.55;
        case 3
            cfg.F = 0.70;
            cfg.CR = 0.60;
            cfg.etaM = 12;
            cfg.guideWeight = 0.15;
            cfg.localBias = 0.30;
        case 4
            cfg.F = 0.45;
            cfg.CR = 0.80;
            cfg.etaM = 18;
            cfg.guideWeight = 0.45;
            cfg.localBias = 0.60;
        otherwise
            cfg.F = 0.50;
            cfg.CR = 0.75;
            cfg.etaM = 20;
            cfg.guideWeight = 0.30;
            cfg.localBias = 0.55;
    end

    decay = 1 - 0.15 * min(gensSinceChange / 10, 1);
    cfg.F = min(max(cfg.F * decay, 0.2), 0.9);
end
